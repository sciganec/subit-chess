'use strict';
const assert=require('assert');
const fs=require('fs');
const html=fs.readFileSync('index.html','utf8');
const scripts=[];
html.replace(/<script\b[^>]*>([\s\S]*?)<\/script>/gi,(_,body)=>{if(body.trim())scripts.push(body);return _;});
assert(scripts.length>0,'index.html must contain an inline application script');
const js=scripts.join('\n');
assert.doesNotThrow(()=>new Function(js),'application JavaScript must parse');
assert(js.includes('function qiGraphOrderRootMoves(moves,pos,ttMove)'), 'graph ordering must live inside makeSearchModule for Worker serialization');
assert(js.includes('moves = orderRootMoves(moves,pos,ttPrevMove);'),'searchRoot must invoke the ordering-mode dispatcher');
assert(js.includes('if(qiGraphEnabled)return qiGraphOrderRootMoves(moves,pos,ttMove);'),'graph and legacy QI modes must be mutually exclusive');
assert(js.includes("qiGraph:'off'"),'graph mode must default OFF');
assert(js.includes("qiGraphEnabled: state.settings.qiGraph === 'on'"),'live search must pass the graph toggle');
assert(js.includes('qiGraphEnabled: !!data.qiGraphEnabled'),'Worker must pass the graph toggle to createSearch');
assert(js.includes('qiGraphEnabled: !!opts.qiGraphEnabled'),'sync fallback and Worker request must pass the graph toggle');
assert(js.includes('GRAPH v0.2.2'),'A/B/C must include graph mode');
assert(js.includes("edgeSchedule:'canonical-UCI-lexicographic'"),'edge schedule must be explicit and deterministic');
assert(js.includes('QI graph changed the legal candidate set'),'candidate-set preservation guard must exist');
assert(js.includes('QI graph unitary norm invariant failed'),'unitary norm guard must exist');
console.log('SUBIT-QI v0.2.2 integration contract: PASS (script syntax, root hook, default-OFF toggle, Worker/fallback propagation, mode isolation, A/B/C, deterministic edge schedule, candidate and norm guards)');
